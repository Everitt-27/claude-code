#!/usr/bin/env node
// Post-process the ts-rs output into a usable TypeScript package.
//
// Two things happen here.
//
// 1. `bigint` becomes `number`. ts-rs maps Rust's 64-bit integers to `bigint`,
//    but serde emits them as JSON numbers and `JSON.parse` produces `number`.
//    Declaring `bigint` would be a lie the compiler happily accepts and the
//    runtime immediately breaks. Every 64-bit value that crosses this boundary
//    is bounded well below 2^53 — money in cents, day counts, sequence numbers —
//    with one exception: the simulation seed, which is transmitted as a
//    hexadecimal string precisely because it does not fit.
//
// 2. An `index.ts` is written re-exporting every generated type, so the web app
//    imports from one place.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const generated = join(here, "..", "packages", "api-schema", "src", "generated");

const files = readdirSync(generated)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .sort();

if (files.length === 0) {
  console.error(
    "No generated bindings found. Run `make schema` (or the cargo test that exports them) first.",
  );
  process.exit(1);
}

let rewritten = 0;
for (const file of files) {
  const path = join(generated, file);
  const before = readFileSync(path, "utf8");
  const after = before.replace(/\bbigint\b/g, "number");
  if (after !== before) {
    writeFileSync(path, after);
    rewritten += 1;
  }
}

const names = files.map((f) => f.replace(/\.ts$/, ""));
const index = [
  "// Generated by scripts/generate-api-schema.mjs. Do not edit by hand.",
  "// Source of truth: the Rust types in crates/*, exported with ts-rs.",
  "",
  ...names.map((n) => `export type { ${n} } from "./generated/${n}";`),
  "",
].join("\n");

writeFileSync(join(generated, "..", "index.ts"), index);
console.log(
  `api-schema: ${names.length} types, ${rewritten} file(s) had bigint rewritten to number`,
);
